#!/usr/bin/env node
// Bundles the publisher into one dependency-free file inside the plugin, because installed plugins
// carry no node_modules. `--check` fails if the committed bundle is out of date (run in CI).
import { build } from 'esbuild';
import { readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pluginDir = join(here, '..', 'plugins', 'operation');
const outfile = join(pluginDir, 'scripts', 'publish-aihub.mjs');
const plugin = JSON.parse(readFileSync(join(pluginDir, '.claude-plugin', 'plugin.json'), 'utf8'));

const result = await build({
  entryPoints: [join(here, 'publisher-entry.mjs')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  outfile,
  legalComments: 'inline',
  define: { __PLUGIN_VERSION__: JSON.stringify(`${plugin.name}@${plugin.version}`) },
  banner: {
    js: [
      '#!/usr/bin/env node',
      '// GENERATED by tools/build-publisher.mjs from tools/lib — do not edit. Run: cd tools && npm run build:publisher',
      "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);",
    ].join('\n'),
  },
});

const code = result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  const current = existsSync(outfile) ? readFileSync(outfile, 'utf8') : '';
  if (current !== code) {
    console.log('✗ plugins/operation/scripts/publish-aihub.mjs is out of date — run: npm run build:publisher');
    process.exit(1);
  }
  console.log('✓ publisher bundle is up to date');
} else {
  const { writeFileSync, mkdirSync, chmodSync } = await import('node:fs');
  mkdirSync(dirname(outfile), { recursive: true });
  writeFileSync(outfile, code);
  chmodSync(outfile, 0o755);
  console.log(`✓ wrote ${outfile} (${Math.round(code.length / 1024)} KB)`);
}
